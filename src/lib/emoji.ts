export const EMOJI_PAGE_SIZE = 48

export function categoryEmojis(category: EmojiCategory): string[] {
  return category.emojis.split(' ').filter(Boolean)
}

export function findEmojis(query: string): string[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return []

  const found: string[] = []
  for (const category of EMOJI_CATEGORIES) {
    for (const emoji of categoryEmojis(category)) {
      const name = EMOJI_NAMES[emoji] ?? ''
      if (emoji.includes(needle) || name.includes(needle)) found.push(emoji)
    }
  }
  return [...new Set(found)]
}